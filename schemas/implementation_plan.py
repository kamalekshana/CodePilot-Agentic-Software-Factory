
from enum import Enum

from pydantic import BaseModel, ConfigDict, Field, model_validator


class TaskPriority(str, Enum):
    HIGH = "high"
    MEDIUM = "medium"
    LOW = "low"


class ImplementationTask(BaseModel):
    """A single task in the implementation plan."""

    model_config = ConfigDict(extra="forbid")

    task_id: str = Field(min_length=1)
    title: str = Field(min_length=1)
    description: str = Field(min_length=1)
    priority: TaskPriority
    dependencies: list[str] = Field(default_factory=list)
    completion_criteria: list[str] = Field(min_length=1)


class ImplementationPlan(BaseModel):
    """Validated implementation plan generated by Planner Agent."""

    model_config = ConfigDict(extra="forbid")

    project_name: str = Field(min_length=1)
    summary: str = Field(min_length=1)
    tasks: list[ImplementationTask] = Field(min_length=1)
    execution_order: list[str] = Field(min_length=1)

    @model_validator(mode="after")
    def validate_plan(self):
        task_ids = [task.task_id for task in self.tasks]

        # Check duplicate task IDs.
        if len(task_ids) != len(set(task_ids)):
            raise ValueError("Duplicate task IDs are not allowed.")

        task_id_set = set(task_ids)

        # Check that every dependency references an existing task.
        for task in self.tasks:
            if len(task.dependencies) != len(set(task.dependencies)):
                raise ValueError(
                    f"Duplicate dependencies found in {task.task_id}."
                )

            if task.task_id in task.dependencies:
                raise ValueError(
                    f"Task {task.task_id} cannot depend on itself."
                )

            for dependency in task.dependencies:
                if dependency not in task_id_set:
                    raise ValueError(
                        f"Unknown dependency '{dependency}' "
                        f"in task {task.task_id}."
                    )

        # Detect circular dependencies using depth-first search.
        graph = {
            task.task_id: task.dependencies
            for task in self.tasks
        }

        visiting = set()
        visited = set()

        def visit(task_id):
            if task_id in visiting:
                raise ValueError(
                    f"Circular dependency detected involving {task_id}."
                )

            if task_id in visited:
                return

            visiting.add(task_id)

            for dependency in graph[task_id]:
                visit(dependency)

            visiting.remove(task_id)
            visited.add(task_id)

        for task_id in task_ids:
            visit(task_id)

        # Validate execution order.
        if len(self.execution_order) != len(set(self.execution_order)):
            raise ValueError("Execution order contains duplicate task IDs.")

        if set(self.execution_order) != task_id_set:
            raise ValueError(
                "Execution order must contain every task ID exactly once."
            )

        order_positions = {
            task_id: index
            for index, task_id in enumerate(self.execution_order)
        }

        # Dependencies must appear before dependent tasks.
        for task in self.tasks:
            for dependency in task.dependencies:
                if order_positions[dependency] >= order_positions[task.task_id]:
                    raise ValueError(
                        f"Dependency {dependency} must appear before "
                        f"{task.task_id} in execution order."
                    )

        return self
